const assert = require('node:assert/strict');
const fs = require('node:fs');
const vm = require('node:vm');
const source = fs.readFileSync(require('node:path').join(__dirname,'../plugins/vmpayment/teya/assets/teya-refund.js'),'utf8');
const elements = {};
for (const name of ['submit','retry','amount','message']) elements[name] = {disabled:false,hidden:false,value:'1.00',textContent:'',listeners:{},addEventListener(event,fn){this.listeners[event]=fn;}};
const timers=[],calls=[];
let confirmations=0;
const panel={dataset:{messages:JSON.stringify({REFUND_BLOCKED:'Automatic retries are paused'}),pending:'1',blocked:'1',token:'csrf',order:'12',key:'original-refund-key',url:'/admin'},querySelector(selector){return elements[{'.teya-refund-submit':'submit','.teya-refund-retry':'retry','.teya-refund-amount':'amount','.teya-refund-message':'message'}[selector]];}};
const document={addEventListener(event,fn){fn();},querySelectorAll(){return [panel];}};
const window={confirm(){confirmations++;return true;},location:{reload(){throw Error('Unexpected reload');}}};
let response={pending:true,blocked:true};
const fetch=async(url,options)=>{calls.push(options);return {ok:true,json:async()=>response};};
vm.runInNewContext(source,{document,window,fetch,URLSearchParams,Date,Error,setTimeout(fn,delay){timers.push({fn,delay});return timers.length;},clearTimeout(){}});
(async()=>{
 assert.equal(timers.length,0,'blocked refund does not automatically retry on page load');
 assert.equal(elements.submit.disabled,true);
 elements.retry.listeners.click();
 await new Promise(setImmediate);
 assert.equal(confirmations,1,'manual retry requires confirmation');
 assert.equal(new URLSearchParams(calls[0].body).get('refund_key'),'original-refund-key');
 assert.equal(timers.length,0,'authorization refusal stops browser retries');
 assert.match(elements.message.textContent,/paused/);
 response={pending:true,retry_at:Math.floor(Date.now()/1000)+7200};
 elements.retry.listeners.click();
 await new Promise(setImmediate);
 assert(timers[0].delay>7198000,'retry respects server cooldown');
 console.log('PASS: blocked refunds stop browser retries; explicit retries preserve reference and honor cooldown');
})().catch(error=>{console.error(error);process.exitCode=1;});
